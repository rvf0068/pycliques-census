"""Second fourth-stage reconstruction: independent intersections and folds.

The P3 input is generated by the existing dual-enumerator proof.
At stage P4, independently check NetworkX facets against the general
bitset Bron--Kerbosch implementation (cap 2,500, above the observed
2,223-facet maximum), build all intersections *pairwise*, and pare via
direct closed-neighborhood inclusions rather than complement-based
containment. All archived adjacency SHA-256s are recomputed.
"""
from __future__ import annotations

import sys

if sys.flags.optimize:
    raise RuntimeError("Optimized independent P4 proof is forbidden")

import networkx as nx

from research.order10_p3_global_v23_index.independent_verify import (
    independent_p3, maximal_cliques_bk,
)
from research.order10_small_p4_98_v1.independent_verify import (
    closed_neighborhood_folds, serialize_sha256, shape,
)
from research.order10_p4_203_ears_v1.verify import require


def replay_independent_p4(record: dict) -> tuple[list[int], list[int]]:
    g = independent_p3(record["graph6"])
    require([len(g), g.number_of_edges()] == record["p3"],
            "Independent reconstruction of the original P3 differs")
    facets_nx = sorted(sum(1 << u for u in q) for q in nx.find_cliques(g))
    facets_bk = maximal_cliques_bk(g, cap=2500)
    require(facets_nx == sorted(facets_bk)
            and len(facets_nx) == record["facets"],
            "Independent P4 NetworkX/Bron--Kerbosch facet lists disagree")
    n = len(facets_nx)
    raw = [0] * n
    for i in range(n):
        a = facets_nx[i]
        for j in range(i + 1, n):
            if a & facets_nx[j]:
                raw[i] |= 1 << j
                raw[j] |= 1 << i
    require(shape(raw) == record["raw_p4"],
            "Independent P4 clique intersection graph differs")
    pared, rounds = closed_neighborhood_folds(raw)
    require(
        rounds == record["fold_rounds"]
        and shape(pared) == record["p4"]
        and serialize_sha256(pared) == record["p4_adj_sha256"],
        f"Independent full fourth-iterate matrix or folding mismatch "
        f"for original McKay {record['index']}",
    )
    return raw, pared
